export function sceneDef(type: string) {
  return SCENES[type];
}

export function availableScenes(collectionSlug: string) {
  return Object.entries(SCENES).filter(([, def]) => !def.onlyFor || def.onlyFor.includes(collectionSlug));
}

export function sourceOf(type: string): "library" | "editorial" | "signature" {
  const g = SCENES[type]?.group;
  return g === "Signature" ? "signature" : g === "Editorial" ? "editorial" : "library";
}
